"""Bring up the dataraum control-plane container for HTTP MCP calls.

Reuses the docker-compose stack shipped in vendor/dataraum-context/. Tests
talk to it over HTTP MCP at http://127.0.0.1:8000/mcp/.

The compose stack persists across test runs (no auto-teardown). End sessions
between strategies via end_session(outcome="delivered") to clear active state.
Wipe with `docker compose -f vendor/dataraum-context/docker-compose.yml down -v`.
"""

from __future__ import annotations

import os
import secrets
import subprocess
from dataclasses import dataclass
from pathlib import Path

EVAL_ROOT = Path(__file__).resolve().parent.parent
VENDOR_DIR = EVAL_ROOT / "vendor" / "dataraum-context"
COMPOSE_FILE = VENDOR_DIR / "docker-compose.yml"
ENV_FILE = EVAL_ROOT / ".docker.env"
DATA_DIR = EVAL_ROOT / "data"

# Path inside the control-plane container where DATA_DIR is bind-mounted.
CONTAINER_SOURCES_DIR = "/var/lib/dataraum/sources"

MCP_URL = "http://127.0.0.1:8000/mcp/"
HEALTH_URL = "http://127.0.0.1:8000/health"


@dataclass(frozen=True)
class StackHandle:
    url: str
    token: str

    def auth_headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.token}"}


def _ensure_env_file() -> str:
    """Create .docker.env if missing; return the MCP token."""
    if ENV_FILE.exists():
        values = _parse_env(ENV_FILE.read_text())
        token = values.get("DATARAUM_MCP_TOKEN", "")
        if token:
            return token

    token = secrets.token_hex(32)
    anthropic_key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not anthropic_key:
        eval_env = EVAL_ROOT / ".env"
        if eval_env.exists():
            anthropic_key = _parse_env(eval_env.read_text()).get("ANTHROPIC_API_KEY", "")

    lines = [
        "# Generated by calibration/stack.py — safe to delete; will be regenerated.",
        "POSTGRES_USER=dataraum",
        "POSTGRES_PASSWORD=dataraum",
        "POSTGRES_DB=dataraum",
        "DUCKLAKE_CATALOG_DB=dataraum_lake_catalog",
        f"HOST_SOURCES_DIR={DATA_DIR}",
        f"DATARAUM_MCP_TOKEN={token}",
        f"ANTHROPIC_API_KEY={anthropic_key}",
    ]
    ENV_FILE.write_text("\n".join(lines) + "\n")
    return token


def _parse_env(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value.strip()
    return out


def _compose(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    cmd = [
        "docker",
        "compose",
        "-f",
        str(COMPOSE_FILE),
        "--env-file",
        str(ENV_FILE),
        *args,
    ]
    return subprocess.run(cmd, check=check, capture_output=True, text=True)


def _health_ok() -> bool:
    import urllib.error
    import urllib.request

    try:
        with urllib.request.urlopen(HEALTH_URL, timeout=2) as resp:
            return bool(resp.status == 200)
    except (urllib.error.URLError, TimeoutError, ConnectionError):
        return False


def up() -> StackHandle:
    """Ensure the compose stack is up; return MCP handle."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    token = _ensure_env_file()

    if _health_ok():
        return StackHandle(url=MCP_URL, token=token)

    print("[stack] Bringing up dataraum control-plane (docker compose up -d --wait)...")
    result = _compose("up", "-d", "--wait", check=False)
    if result.returncode != 0:
        raise RuntimeError(
            f"docker compose up failed (rc={result.returncode}):\n"
            f"stdout:\n{result.stdout}\n"
            f"stderr:\n{result.stderr}"
        )

    if not _health_ok():
        raise RuntimeError(f"Control plane unhealthy after compose up. {HEALTH_URL} did not respond.")

    return StackHandle(url=MCP_URL, token=token)


def down(volumes: bool = False) -> None:
    """Stop the compose stack."""
    args = ["down"]
    if volumes:
        args.append("-v")
    _compose(*args, check=False)


def container_path_for(strategy: str) -> str:
    """Translate host data/{strategy} to its in-container path."""
    return f"{CONTAINER_SOURCES_DIR}/{strategy}"
